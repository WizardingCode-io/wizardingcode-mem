import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, realpathSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { resolveProject } from "../../src/core/project.ts";
import type { Redacted } from "../../src/core/redact.ts";
import type { MemoryKind } from "../../src/core/types.ts";
import { loadModel, type Model, modelPath } from "../../src/embed/model.ts";
import { writeMemoryVector } from "../../src/embed/vectors.ts";
import { searchMemories, type ToolContext } from "../../src/mcp/tools.ts";
import { semanticCandidates } from "../../src/retrieve/semantic.ts";
import { type Db, openDb } from "../../src/store/db.ts";
import { insertMemory } from "../../src/store/memories.ts";
import { listMemories, searchAll } from "../../src/ui/api.ts";
import { searchTerms } from "../../src/util/words.ts";
import golden from "./retrieval.json" with { type: "json" };
import semantic from "./semantic.json" with { type: "json" };

// Explicit search (memory_search, the viewer's list and palette) over the golden set.
// Without a model it must answer exactly as it did before search by meaning existed:
// the snapshot was recorded on the lexical-only code and is never regenerated by hand.

const NOW = Date.UTC(2026, 9, 5);
let base: string;
let db: Db;
let projectId: number;
const ids = new Map<string, number>();

beforeAll(() => {
  base = realpathSync(mkdtempSync(join(tmpdir(), "wizardingcode-mem-search-")));
  const project = join(base, "project");
  mkdirSync(project);
  db = openDb({ dataDir: join(base, "data"), busyTimeoutMs: 2000 });
  projectId = resolveProject(db, project, NOW).id;
  for (const memory of golden.memories) {
    ids.set(
      memory.key,
      insertMemory(db, {
        projectId,
        kind: memory.kind as MemoryKind,
        title: memory.title,
        body: memory.body as Redacted,
        terms: searchTerms(memory.title, memory.body, memory.files),
        importance: 3,
        branch: null,
        commit: null,
        origin: "manual",
        judge: "heuristic",
        judgeVersion: "1",
        sourceTurnId: null,
        files: memory.files.map((path) => ({ path, role: "changed" as const })),
        now: NOW,
      }),
    );
  }
});
afterAll(() => {
  db.close();
  rmSync(base, { recursive: true, force: true });
});

const QUERIES = [
  "",
  ...golden.relevant.map((item) => item.prompt),
  ...golden.unrelated,
  ...semantic.paraphrases.map((item) => item.prompt),
  ...semantic.unrelated,
];

const tool = (scope: number | null, model: Model | null = null): ToolContext => ({
  db,
  judge: null as never,
  projectId: scope,
  root: "",
  branch: null,
  now: NOW,
  model,
});

describe("explicit search without a model", () => {
  test("memory_search, the list and the palette answer as they did before", () => {
    const outputs = QUERIES.map((query) => ({
      query,
      project: searchMemories(tool(projectId), { query }),
      projectFixes: searchMemories(tool(projectId), { query, kind: "fix" }),
      global: searchMemories(tool(null), { query, limit: 5 }),
      list: listMemories(db, { projectId, q: query, limit: 10 }, null).items.map((item) => item.id),
      palette: searchAll(db, query, 10, null).map((hit) => hit.id),
    }));
    expect(outputs).toMatchSnapshot();
  });
});

// With the model. The subset pack holds every piece of the golden texts, so for them its
// vectors are the full model's: the numbers below are those measured with the full pack
// (scripts/embed/search-floor.ts, ADR 0017). Text outside the golden set, such as gibberish,
// needs the full pack: that case runs only when WIZARDINGCODE_MEM_EMBED_PACK points to it.

const TOP = 5;
const SHOWN = 10;
const PORTUGUESE = /[ãõçáéíóúâêô]|^(o|a|os|as|posso|dois|porque) /i;
const GIBBERISH = [
  "qwxz blorptang fizzleborp vrmmk",
  "asdf jkl qwerty uiop",
  "kjhgf dsapoiu ytrewq",
  "frobnicate the wibble",
  "xyzzy plugh",
  "aaaaaaa bbbbbb",
];

function withPack(pack: string) {
  let model: Model;
  beforeAll(() => {
    const dataDir = join(base, `model-${Math.random().toString(36).slice(2)}`);
    mkdirSync(join(dataDir, "models"), { recursive: true });
    copyFileSync(pack, modelPath(dataDir));
    const loaded = loadModel({ dataDir, env: {} });
    if (loaded === null) throw new Error(`${pack} did not load`);
    model = loaded;
    for (const memory of golden.memories) {
      writeMemoryVector(db, model, ids.get(memory.key) as number, memory.title, memory.body);
    }
  });
  const ranked = (query: string, withModel: boolean) =>
    [
      ...searchMemories(tool(projectId, withModel ? model : null), { query }).matchAll(
        /#(\d+) \[/g,
      ),
    ].map((m) => Number(m[1]));
  const inTop = (items: { prompt: string; expect: string[] }[], withModel: boolean) =>
    items.filter((item) =>
      item.expect.every((key) =>
        ranked(item.prompt, withModel)
          .slice(0, TOP)
          .includes(ids.get(key) as number),
      ),
    ).length;
  const semanticOnly = (query: string) => {
    const lexical = new Set(ranked(query, false));
    return ranked(query, true)
      .slice(0, SHOWN)
      .filter((id) => !lexical.has(id)).length;
  };
  return {
    paraphrases: () => {
      const all = [...golden.relevant, ...semantic.paraphrases];
      const portuguese = semantic.paraphrases.filter(
        (item) =>
          PORTUGUESE.test(item.prompt) &&
          item.expect.every((key) => key !== "pt-lingua" && key !== "pt-cursor"),
      );
      return {
        all: [inTop(all, false), inTop(all, true), all.length],
        portuguese: [inTop(portuguese, false), inTop(portuguese, true), portuguese.length],
      };
    },
    noise: () => {
      const unrelated = [...golden.unrelated, ...semantic.unrelated];
      const perQuery = (queries: string[]) =>
        queries.reduce((n, query) => n + semanticOnly(query), 0) / queries.length;
      return {
        found: unrelated.reduce((n, query) => n + semanticOnly(query), 0),
        queries: unrelated.length,
        // Each set read on its own too (ruling R3): the coding-flavoured one is the noisier.
        worstSet: Math.max(perQuery(golden.unrelated), perQuery(semantic.unrelated)),
      };
    },
    gibberish: () =>
      GIBBERISH.map((query) => ({
        query,
        meaning: semanticCandidates(db, model, query, { projectId: null, limit: 50 }),
      })).filter((item) => item.meaning.length > 0),
  };
}

describe("explicit search with the model (subset pack)", () => {
  const golden_ = withPack(join(import.meta.dir, "../fixtures/embed/subset.wcpack"));

  test("paraphrases reach the top 5, Portuguese ones of English memories too", () => {
    const { all, portuguese } = golden_.paraphrases();
    console.log(
      `top ${TOP}: ${all[0]}/${all[2]} → ${all[1]}/${all[2]}; Portuguese of English: ${portuguese[0]}/${portuguese[2]} → ${portuguese[1]}/${portuguese[2]}`,
    );
    // Measured at the floor's calibration (0.32): 35/44 → 39/44, Portuguese 1/8 → 4/8.
    expect(all[1]).toBeGreaterThanOrEqual(39);
    expect(portuguese[2]).toBe(8);
    expect(portuguese[1]).toBeGreaterThanOrEqual(4);
  });

  test("an unrelated query gets at most one memory by meaning alone, on average", () => {
    const { found, queries, worstSet } = golden_.noise();
    console.log(`semantic-only results for unrelated queries: ${found}/${queries}`);
    expect(found / queries).toBeLessThanOrEqual(1);
    expect(worstSet).toBeLessThanOrEqual(1);
  });
});

const fullPack = process.env.WIZARDINGCODE_MEM_EMBED_PACK;
describe.skipIf(!fullPack || !existsSync(fullPack))("explicit search with the full pack", () => {
  const full = withPack(fullPack as string);

  test("the same numbers as with the subset", () => {
    const { all, portuguese } = full.paraphrases();
    expect(all[1]).toBeGreaterThanOrEqual(39);
    expect(portuguese[1]).toBeGreaterThanOrEqual(4);
    const { found, queries, worstSet } = full.noise();
    expect(found / queries).toBeLessThanOrEqual(1);
    expect(worstSet).toBeLessThanOrEqual(1);
  });

  test("gibberish finds nothing by meaning", () => {
    expect(full.gibberish()).toEqual([]);
  });
});
